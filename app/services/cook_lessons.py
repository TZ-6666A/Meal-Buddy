def lookup_recipe(dish: str) -> dict | None:
    """按去掉空白后的菜名精确匹配。"""
    key = "".join((dish or "").split())
    found = LOCAL_RECIPES.get(key)
    if found is None:
        return None
    return {
        "dish": found["dish"],
        "servings": found["servings"],
        "note": found["note"],
        "ingredients": [dict(item) for item in found["ingredients"]],
        "steps": [dict(item) for item in found["steps"]],
    }


